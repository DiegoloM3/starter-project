import 'dart:async';

import 'package:flutter/widgets.dart';
import 'package:news_app_clean_architecture/app.dart';
import 'package:news_app_clean_architecture/injection_container.dart';

/// Application entry point shared across flavors.
///
/// Responsibilities (kept tiny on purpose):
///   1. Bind the Flutter engine.
///   2. Initialise platform services (Firebase once `flutterfire configure`
///      runs — see [docs/prueba-tecnica/01_PLAN_FASES.md] Fase 0).
///   3. Register cross-cutting error handlers (added in B2.7).
///   4. Wire DI via [initializeDependencies].
///   5. Hand control over to [MyApp] inside a guarded zone.
Future<void> bootstrap() async {
  await runZonedGuarded(
    () async {
      WidgetsFlutterBinding.ensureInitialized();

      // TODO(F0): enable Firebase initialisation once firebase_options.dart
      // is generated by `flutterfire configure`. Template:
      //   await Firebase.initializeApp(
      //     options: DefaultFirebaseOptions.currentPlatform,
      //   );

      await initializeDependencies();

      runApp(const MyApp());
    },
    (error, stack) {
      // Global zone-level error trap. B2.7 wires this into AppLogger.
      // For now we let the error surface so Flutter's default reporter
      // still shows it during development.
    },
  );
}
