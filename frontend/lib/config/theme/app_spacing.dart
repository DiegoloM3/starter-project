/// Spacing scale (4 dp base grid). Use for padding, gaps and sizes instead of
/// raw numeric literals.
class AppSpacing {
  AppSpacing._();

  static const double xs = 4.0; // icon gap, badge padding
  static const double sm = 8.0; // tight padding, chip gap
  static const double md = 12.0; // section padding
  static const double lg = 16.0; // card padding, list item
  static const double xl = 20.0; // article body padding
  static const double xl2 = 24.0; // section gap
  static const double xl3 = 32.0; // screen section gap
  static const double xl4 = 48.0; // hero spacing
  static const double gutter = 16.0; // horizontal page margin
}
